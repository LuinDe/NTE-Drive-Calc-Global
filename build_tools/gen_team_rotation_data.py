"""Generate ``src/services/team_rotation_data.py`` (the user-approved per-character rotations).

Source of truth: ``work/rotation_research/research_result.json``.  For every character the verified
``verify.corrected_steps`` override ``research.steps``.  All 24 rotations were approved by the user
(2026-10-03); the module stores them as variant ``"approved"``.

Every runnable step (``sim_supported`` with an ``ability_id``) is validated against the animation
candidates in ``work/rotation_research/action_catalog.json`` with strict per-character
``(ability_id, selector)`` matching -- no fallback.  The NORMAL_ENTRY substitutes, the
QTE_SEQ_OVERRIDE target step, the gauge-setting steps and the time-stop keys are validated too.

Form steps (schema 2): ``src/services/team_form_actions.py`` (generated by gen_team_form_actions.py from the
static DB) lists approved steps whose transformed-state attacks were time-only.  They become runnable steps
keyed by the form action ``(form ability, "Form:<Name>")``; ``combo`` holds every action the step runs in
order, ``form_role`` / ``group`` tell the simulator how the step sits in its form window.  Their keys are
validated against ``FORM_ACTIONS`` (with hits for each GE), not against action_catalog.json.  The plain
ultimate of Zankou's step #8 is replaced by the force ultimate the recordings show (``replaces``).
Run gen_team_form_actions.py first.  Any validation error aborts before anything is written.

Implements implementation brief section 4.1 (work/cycle_sim/brief.md).

usage: gen_team_rotation_data.py [--check] [--out PATH]
  --check   write nothing; exit 1 when the module on disk differs from what would be generated
  --out     output path (default: work/l10n_root/src/services/team_rotation_data.py)

Run with the Python 3.11 interpreter (PYTHONUTF8=1).  Reads the static DB read-only.
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import json
import re
import sqlite3
import sys
from pathlib import Path

SP = Path(__file__).resolve().parent.parent          # scratchpad/v230
WORK = SP / "work"
RESEARCH = WORK / "rotation_research" / "research_result.json"
CATALOG = WORK / "rotation_research" / "action_catalog.json"
STATIC = WORK / "l10n_root" / "data" / "game_static.sqlite3"
OUT = WORK / "l10n_root" / "src" / "services" / "team_rotation_data.py"
FORM_MODULE = WORK / "l10n_root" / "src" / "services" / "team_form_actions.py"

SCHEMA_VERSION = 2
VARIANT = "approved"
STEP_FIELDS = ("seq", "slot", "ability_id", "selector", "repeat", "entry_only", "sim", "est_s",
               "gauge_set", "label_ko", "combo", "form_role", "group")
SLOT_BY_INDEX = {1: "basic", 2: "skill", 3: "ultimate", 4: "qte"}
HAN = re.compile("[㐀-䶿一-鿿豈-﫿]")   # CJK ideographs (label_ko must be Korean only)
RING = ("cosmos", "nature", "incantation", "chaos", "psyche", "lakshana")

# Brief 1.2 (inference): these skills set the caster's cycle gauge to 100.
GAUGE_FILL = {("GA_Female051_Skill", "Default"): 100.0, ("GA_BlackBird_Skill", "Default"): 100.0}
# Zankou passive "进入战斗时，残虹的「环合值」为100点" (verified text).
STARTS_FULL = {1036}
# Brief 3: substitutes prepended on a normal (non support-skill) entry.
NORMAL_ENTRY = {
    1019: ("GA_Mint019_Appear", "AirAttackEnd"),
    1020: ("GA_Haniel_Appear", "AirAttackEnd"),
    1021: ("GA_Edgar_Appear", "AirAttackEnd"),
}
# Brief 3: ultimate time-stop durations (s), measured, user records 1–3 (pause mask 8).
Q_TIME_STOP_S = {
    "GA_Sagiri_UltraSkill": 3.51,
    "GA_Lacrimosa_UltraSkill": 4.20,
    "GA_Daffodill_UltraSkill": 5.08,
    "GA_Zankou_UltraSkillMagic": 5.71,
    "GA_Zankou_UltraSkillForce": 4.83,     # the second ultimate is always the force variant (captures 1/2/4)
    "GA_Oneiroi_UltraSkill": 3.98,
    "GA_Radio072_UltraSkill": 11.0,
}
# Brief 3: Shinku's support skill is step #8 (step #1 is an unsupported pre-battle wait).
QTE_SEQ_OVERRIDE = {1076: 8}


def role_of(field_s: float) -> str:
    return "support" if field_s <= 8.5 else ("sub" if field_s < 15.0 else "main")


def _fmt_step(step: dict) -> str:
    return "{" + ", ".join(f"{k!r}: {step[k]!r}" for k in STEP_FIELDS) + "}"


def load_form_module(path: Path = FORM_MODULE) -> tuple[dict, str]:
    """The generated form-action module as a namespace (executed from its file; no src import)."""
    raw = path.read_bytes()
    ns: dict = {}
    exec(compile(raw.decode("utf-8"), str(path), "exec"), ns)  # noqa: S102 - our own generated data
    return ns, hashlib.sha256(raw).hexdigest()


def render(source_sha: str, catalog_sha: str, characters: dict, names: dict, stop_owner: dict,
           form_sha: str = "") -> str:
    out = [
        "# 队伍模拟：已审核的角色循环（由 research_result.json 生成，勿手改）",
        "# GENERATED FILE - DO NOT EDIT.  Regenerate with scratchpad/v230/tools/gen_team_rotation_data.py",
        f"# validated against action_catalog.json sha256 {catalog_sha}",
        f"# form steps from team_form_actions.py sha256 {form_sha}",
        '"""Approved per-character rotations for the team simulator (generated, do not edit).',
        "",
        "CHARACTERS[cid] = {name_zh, element, role, field_time_s, verdict, confidence, starts_full_gauge,",
        'variants: {"approved": {"steps": [...]}}}.  Step fields: seq, slot (basic|skill|ultimate|qte|other),',
        "ability_id, selector, repeat, entry_only (the support-skill entry step), sim (runnable on the",
        "animation axis), est_s (research estimate in seconds; None = unknown), gauge_set (cycle gauge value",
        "set after the step, or None), label_ko, combo (form steps: every (ability_id, selector) action the",
        "step runs in order, from team_form_actions.FORM_ACTIONS; None otherwise), form_role (body | terminal |",
        "tail | after | window | free | exit, or None) and group (body group inside the form window, or None).",
        "",
        "label_ko is a Korean-only tooltip: show it only when the UI language is ko, never in zh/en/ja.",
        '"""',
        "",
        f"SCHEMA_VERSION = {SCHEMA_VERSION}",
        f"SOURCE_SHA256 = {source_sha!r}",
        "",
        "CHARACTERS = {",
    ]
    for cid, c in characters.items():
        out.append(f"    {cid}: {{")
        for key in ("name_zh", "element", "role", "field_time_s", "verdict", "confidence", "starts_full_gauge"):
            out.append(f"        {key!r}: {c[key]!r},")
        out.append(f"        'variants': {{{VARIANT!r}: {{'steps': [")
        for st in c["variants"][VARIANT]["steps"]:
            out.append(f"            {_fmt_step(st)},")
        out.append("        ]}},")
        out.append("    },")
    out.append("}")
    out += ["", "# Normal (non support-skill) entry: prepend this (ability_id, selector) instead of the support skill.",
            "NORMAL_ENTRY = {"]
    for cid, pair in NORMAL_ENTRY.items():
        out.append(f"    {cid}: {pair!r},  # {names[cid]}")
    out += ["}", "", "# Ultimate time-stop seconds by ability_id: measured, user records 1–3 (pause mask 8).",
            "Q_TIME_STOP_S = {"]
    for ab, s in Q_TIME_STOP_S.items():
        out.append(f"    {ab!r}: {s!r},  # {stop_owner[ab]} {names[stop_owner[ab]]}")
    out += ["}", "", "# Support-skill step seq when it is not step 1 (moved to the front on a support-skill entry).",
            f"QTE_SEQ_OVERRIDE = {QTE_SEQ_OVERRIDE!r}", ""]
    return "\n".join(out)


def build(research: Path = RESEARCH, catalog_path: Path = CATALOG,
          static: Path = STATIC, form_module: Path = FORM_MODULE) -> tuple[str, list[str], list[str]]:
    """Return (module text, errors, summary lines); text is empty when validation failed."""
    errors: list[str] = []
    info: list[str] = []
    forms_ns, form_sha = load_form_module(form_module)
    form_actions = forms_ns["FORM_ACTIONS"]
    form_steps = forms_ns["FORM_STEPS"]
    form_rules = forms_ns["FORMS"]
    exit_seqs = {(cid, r["exit_seq"]) for cid, r in form_rules.items() if r.get("exit_seq")}
    used_form_steps: set = set()
    raw = research.read_bytes()
    raw_cat = catalog_path.read_bytes()
    data = json.loads(raw)
    catalog = {int(x["character_id"]): x for x in json.loads(raw_cat)}
    cands = {cid: {(a["ability_id"], a["selector"]): a for a in x["animation_candidates"]}
             for cid, x in catalog.items()}

    con = sqlite3.connect(f"file:{static.as_posix()}?mode=ro", uri=True)
    try:
        element = {int(cid): str(et).rsplit("_", 1)[-1].lower()
                   for cid, et in con.execute("SELECT character_id, element_type FROM character")}
        slot_of = {(int(cid), sid): SLOT_BY_INDEX.get(int(idx), "other")
                   for cid, sid, idx in con.execute("SELECT character_id, skill_id, ability_index FROM character_skill")}
        ability_known = {r[0] for r in con.execute("SELECT ability_id FROM gameplay_ability_catalog")}
        templates = {int(r[0]) for r in con.execute("SELECT character_id FROM character_graduation_template")}
    finally:
        con.close()

    characters: dict[int, dict] = {}
    names: dict[int, str] = {}
    stats = collections.Counter()
    slots = collections.Counter()
    no_trigger_end, no_damage, est_none, est_diff = [], [], [], []
    gauge_hits = collections.Counter()
    for block in data["results"]:
        verify = {int(v["character_id"]): v for v in block["verify"]["characters"]}
        for c in block["research"]["characters"]:
            cid = int(c["character_id"])
            if cid in characters:
                errors.append(f"{cid}: duplicate character in research_result.json")
                continue
            v = verify.get(cid)
            if v is None:
                errors.append(f"{cid}: no verify entry")
                v = {}
            steps = v.get("corrected_steps") or c["steps"]
            stats["from_corrected" if v.get("corrected_steps") else "from_research"] += 1
            if cid not in catalog:
                errors.append(f"{cid}: not in action_catalog.json")
            if cid not in element:
                errors.append(f"{cid}: not in static character table")
                continue
            if element[cid] not in RING:
                errors.append(f"{cid}: element {element[cid]!r} not on the ring")
            if cid in catalog and catalog[cid].get("element") != element[cid]:
                errors.append(f"{cid}: catalog element {catalog[cid].get('element')} != static {element[cid]}")
            entry_seq = QTE_SEQ_OVERRIDE.get(cid, 1)
            out_steps = []
            for i, st in enumerate(steps):
                seq = int(st.get("order") or i + 1)
                if seq != i + 1:
                    errors.append(f"{cid}#{seq}: step order is not contiguous (position {i + 1})")
                ab, sel = st.get("ability_id") or None, st.get("selector") or None
                sim = bool(st.get("sim_supported")) and bool(ab)
                if bool(st.get("sim_supported")) and not ab:
                    errors.append(f"{cid}#{seq}: sim_supported without ability_id")
                slot = slot_of.get((cid, ab), "other") if ab else "other"
                est = st.get("est_duration_s")
                est_s = None if est is None else round(float(est), 3)
                repeat = max(1, int(st.get("repeat") or 1))
                combo = form_role = group = None
                overlay = form_steps.get((cid, seq))
                if overlay is not None:
                    used_form_steps.add((cid, seq))
                    if sim and overlay.get("replaces") != (ab, sel):
                        errors.append(f"{cid}#{seq}: form overlay on the runnable step {ab}/{sel} "
                                      f"(replaces {overlay.get('replaces')})")
                    if not sim and overlay.get("replaces"):
                        errors.append(f"{cid}#{seq}: overlay says it replaces {overlay['replaces']} but the step "
                                      f"is time-only")
                    keys = tuple(tuple(k) for k in overlay["actions"])
                    bad = [k for k in keys if k not in form_actions or not form_actions[k]["hits"]
                           or form_actions[k]["character_id"] != cid]
                    if not keys or bad:
                        errors.append(f"{cid}#{seq}: NO FORM ACTION {bad or keys}")
                    else:
                        ab, sel = keys[0]
                        combo = keys
                        sim = True
                        slot = overlay["slot"]
                        repeat = int(overlay["repeat"])
                        form_role = overlay["role"]
                        group = overlay["group"]
                        est_s = round(sum(form_actions[k]["length_s"] for k in keys), 3)
                        stats["form_steps"] += 1
                elif (cid, seq) in exit_seqs:
                    form_role = "exit"
                label = str(st.get("action_ko") or "").strip()
                if not label:
                    errors.append(f"{cid}#{seq}: empty action_ko")
                if HAN.search(label):       # Korean-only tooltip: no untranslated Chinese
                    errors.append(f"{cid}#{seq}: action_ko contains Chinese characters: {label!r}")
                stats["steps"] += 1
                slots[slot] += 1
                if sim and combo is not None:
                    stats["runnable"] += 1
                    stats["matched_form"] += 1
                elif sim:
                    stats["runnable"] += 1
                    cand = cands.get(cid, {}).get((ab, sel))
                    if cand is None:
                        have = sorted(s for a, s in cands.get(cid, {}) if a == ab)
                        errors.append(f"{cid}#{seq}: NO CANDIDATE {ab}/{sel} (selectors for {ab}: {have})")
                    else:
                        stats["matched"] += 1
                        length = (cand.get("trigger_end_s") or [cand.get("duration_s")])[0]
                        if not cand.get("trigger_end_s"):
                            no_trigger_end.append(f"{cid}#{seq}")
                        if not cand.get("damage_effects"):
                            no_damage.append(f"{cid}#{seq}")
                        if est_s is not None and length is not None and abs(est_s - float(length)) > 0.05:
                            est_diff.append(f"{cid}#{seq}({est_s}s vs anim {length}s)")
                else:
                    stats["time_only"] += 1
                    if est_s is None:
                        est_none.append(f"{cid}#{seq}")
                gauge_set = GAUGE_FILL.get((ab, sel)) if sim else None
                if gauge_set is not None:
                    gauge_hits[(ab, sel)] += 1
                entry_only = seq == entry_seq and slot == "qte" and sim
                out_steps.append({
                    "seq": seq, "slot": slot, "ability_id": ab, "selector": sel,
                    "repeat": repeat, "entry_only": entry_only, "sim": sim,
                    "est_s": est_s, "gauge_set": gauge_set, "label_ko": label,
                    "combo": combo, "form_role": form_role, "group": group,
                })
            entries = [s for s in out_steps if s["entry_only"]]
            if len(entries) != 1:
                errors.append(f"{cid}: expected exactly one support-skill entry step at #{entry_seq}, got "
                              f"{[s['seq'] for s in entries]}")
            field_s = float(c.get("field_time_s") or 0.0)
            names[cid] = str(c["name_zh"])
            characters[cid] = {
                "name_zh": str(c["name_zh"]),
                "element": element[cid],
                "role": role_of(field_s),
                "field_time_s": field_s,
                "verdict": v.get("verdict"),
                "confidence": v.get("final_confidence") or c.get("confidence"),
                "starts_full_gauge": cid in STARTS_FULL,
                "variants": {VARIANT: {"steps": out_steps}},
            }
    characters = dict(sorted(characters.items()))

    for key in sorted(set(form_steps) - used_form_steps):
        errors.append(f"FORM_STEPS {key}: no such approved step")
    for cid, rule in form_rules.items():
        seqs = {s["seq"]: s for s in characters.get(cid, {}).get("variants", {}).get(VARIANT, {}).get("steps", [])}
        for k in ("exit_seq", "terminal_seq", "tail_seq", "window_seq"):
            if rule.get(k) and rule[k] not in seqs:
                errors.append(f"FORMS {cid}: {k} #{rule[k]} is not an approved step")
        for seq in rule.get("body_seqs") or ():
            if seq not in seqs or not seqs[seq]["sim"]:
                errors.append(f"FORMS {cid}: body step #{seq} is not runnable")
        start = tuple(rule["start"][:2])
        if not any((s["ability_id"], s["selector"]) == start for s in seqs.values()):
            errors.append(f"FORMS {cid}: no approved step enters the form with {start}")
    if set(characters) != templates:
        errors.append(f"characters != graduation templates: extra {sorted(set(characters) - templates)}, "
                      f"missing {sorted(templates - set(characters))}")
    for cid, (ab, sel) in NORMAL_ENTRY.items():
        if cid not in characters:
            errors.append(f"NORMAL_ENTRY {cid}: character not in rotations")
        if (ab, sel) not in cands.get(cid, {}):
            errors.append(f"NORMAL_ENTRY {cid}: NO CANDIDATE {ab}/{sel}")
    for cid, seq in QTE_SEQ_OVERRIDE.items():
        steps = characters.get(cid, {}).get("variants", {}).get(VARIANT, {}).get("steps", [])
        hit = [s for s in steps if s["seq"] == seq]
        if not hit or hit[0]["slot"] != "qte" or not hit[0]["sim"]:
            errors.append(f"QTE_SEQ_OVERRIDE {cid}: step #{seq} is not a runnable support-skill step")
    for key in GAUGE_FILL:
        if not gauge_hits[key]:
            errors.append(f"GAUGE_FILL {key}: no approved step uses it")
    stop_owner: dict[str, int] = {}
    for ab in Q_TIME_STOP_S:
        if ab not in ability_known:
            errors.append(f"Q_TIME_STOP_S {ab}: not in gameplay_ability_catalog")
        # owner = the character whose ultimate slot (ability_index 3) prefixes the key
        owners = [cid for cid in characters if (catalog.get(cid, {}).get("skill_slots") or {}).get("3")
                  and ab.startswith(catalog[cid]["skill_slots"]["3"])]
        if len(owners) != 1:
            errors.append(f"Q_TIME_STOP_S {ab}: expected one owning character, got {owners}")
            continue
        stop_owner[ab] = owners[0]
    for ab in Q_TIME_STOP_S:          # a form ultimate's stop must be keyed by the ability its step runs
        if not any(s["ability_id"] == ab for c in characters.values() for s in c["variants"][VARIANT]["steps"]):
            errors.append(f"Q_TIME_STOP_S {ab}: no approved step runs it")
    ult_steps = {(cid, s["ability_id"]) for cid, c in characters.items()
                 for s in c["variants"][VARIANT]["steps"] if s["slot"] == "ultimate" and s["sim"]}
    no_stop = sorted({cid for cid, ab in ult_steps if ab not in Q_TIME_STOP_S})
    unused_stop = sorted(set(Q_TIME_STOP_S) - {ab for _, ab in ult_steps})

    source_sha = hashlib.sha256(raw).hexdigest()
    catalog_sha = hashlib.sha256(raw_cat).hexdigest()
    info += [
        f"source  {research.name} sha256 {source_sha}",
        f"catalog {catalog_path.name} sha256 {catalog_sha}",
        f"characters {len(characters)} (corrected_steps {stats['from_corrected']}, research.steps {stats['from_research']})",
        f"steps {stats['steps']} | runnable {stats['runnable']} | matched (strict ability_id+selector) "
        f"{stats['matched']}/{stats['runnable'] - stats['matched_form']} | form actions "
        f"{stats['matched_form']} | time-only {stats['time_only']}",
        f"form module {form_module.name} sha256 {form_sha} (form steps {stats['form_steps']})",
        f"slots {dict(sorted(slots.items()))}",
        f"entry_only steps {sum(1 for c in characters.values() for s in c['variants'][VARIANT]['steps'] if s['entry_only'])}"
        f" (QTE_SEQ_OVERRIDE {QTE_SEQ_OVERRIDE})",
        f"time-only steps with est_s=None (simulator uses its default): {est_none}",
        f"runnable steps without trigger_end (duration fallback): {no_trigger_end}",
        f"runnable steps without damage effects: {no_damage}",
        f"est_s differs from animation length by >0.05 s: {est_diff}",
        f"gauge_set steps: {dict((f'{a}/{s}', n) for (a, s), n in gauge_hits.items())}",
        f"NORMAL_ENTRY validated: {sorted(NORMAL_ENTRY)}",
        f"ultimates without a measured time stop: {no_stop}",
        f"Q_TIME_STOP_S keys not used by any runnable approved step: {unused_stop}",
        f"roles {dict(collections.Counter(c['role'] for c in characters.values()))}",
    ]
    if errors:
        return "", errors, info
    text = render(source_sha, catalog_sha, characters, names, stop_owner, form_sha)
    compile(text, "team_rotation_data.py", "exec")
    ns: dict = {}
    exec(text, ns)  # noqa: S102 - round-trip check of our own generated data
    if ns["CHARACTERS"] != characters or ns["NORMAL_ENTRY"] != NORMAL_ENTRY \
            or ns["Q_TIME_STOP_S"] != Q_TIME_STOP_S or ns["QTE_SEQ_OVERRIDE"] != QTE_SEQ_OVERRIDE:
        errors.append("round-trip of the generated module does not reproduce the data")
    return text, errors, info


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="do not write; fail if the output is stale")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    text, errors, info = build()
    for line in info:
        print(line)
    if errors:
        print(f"\nVALIDATION FAILED ({len(errors)}):", file=sys.stderr)
        for e in errors:
            print("  -", e, file=sys.stderr)
        return 2
    data = text.encode("utf-8")
    if args.check:
        current = args.out.read_bytes() if args.out.is_file() else b""
        if current != data:
            print(f"STALE: {args.out} differs from the generated module", file=sys.stderr)
            return 1
        print(f"up to date: {args.out}")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(data)                     # LF line endings, like the rest of src/
    print(f"wrote {args.out} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
