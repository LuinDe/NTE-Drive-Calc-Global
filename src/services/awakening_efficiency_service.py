# 角色觉醒（韩文界面「돌파」）效率表（Global）：在单人已审核循环中逐个开启觉醒效果、共鸣与全部觉醒，按 DPS 变化比较；预先计算的数据、本机缓存与后台重新计算。
"""Character awakening efficiency table (Global; Korean UI "돌파 효율").

One cell = one character alone on its reviewed rotation (team simulation ``solo_session``), graduation template,
the basis arc at refinement 1 (the exclusive arc when the character has one - then the row equals the arc efficiency
table's 100 % row -, else the template's arc), ``loops`` passes, first visit "opener", Global arc corrections B1-B4
and the awakening node rules (``awakening_node_rules``) on, the Global live overlay at its default groups.  Rows: every
character with a graduation template and an approved rotation (24, user decision 2026-10-18), not only the eleven
of the arc table.

Variants of one character (``VARIANTS``; design_final §3.2): ``A0`` (no awakening), ``+EffectN`` (level 1, only that
effect), ``R3`` / ``R6`` (level 3 / 6, no effect selected: the resonances and the skill level +1 alone), ``A6`` (the
template's own selection = all six), ``-EffectN`` (the template's selection without that effect, level kept).
Cells (``build_matrix``) are DPS changes in % (DPS = damage / battle time without time stops):
  add one     EffectN: DPS(+EffectN) / DPS(A0) - 1          (default basis)
  remove one  EffectN: DPS(A6) / DPS(-EffectN) - 1          (what the effect adds to a full awakening)
  resonance 3: DPS(R3) / DPS(A0) - 1, resonance 6: DPS(R6) / DPS(R3) - 1, full: DPS(A6) / DPS(A0) - 1 (both bases)
A pair whose cycle end differs by 1 ms or more is marked (time changed).  |x| < 0.05 % is never shown as "+0.0%".

Cell classes (``node_class``) come from the node rules' metadata (``awakening_node_rules.NodeInfo``): damage (a
number), expected value (a number priced from a condition the simulator cannot reproduce), team only, needs
measurement, not computable, under review, upper bound.  A node that is not priced is marked, never shown as 0 %.

Delivery (three layers, the arc table's design): L1 = ``awakening_efficiency_data`` (generated by
``gen_awakening_efficiency_data.py``), L2 = ``<config>/awakening_efficiency_cache.json``, L3 = the page's memory.
Identity = the arc table's (``arc_efficiency_service.Identity``: algorithm, DB sha256, engine fingerprint, arc
corrections, template Puka level) with this module's own ``ALGO_VERSION`` and fingerprint (source closure of this
module), plus the resource level and the node-rule / overlay switch state (L1 serves the shipped defaults only).
Recomputation shares ``arc_efficiency_service._COMPUTE_LOCK`` (one efficiency computation at a time).

Dev switch: ``NTE_AWAKEN_EFF_FORCE_STALE=1`` ignores L1 and L2.  Qt-free.
"""
