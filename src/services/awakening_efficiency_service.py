@dataclass(frozen=True)
class AwakeningEntry:
    character_id: int
    name_zh: str
    element: str
    role: str
    confidence: str
    fork_id: str                    # basis arc (refinement 1): the exclusive arc when there is one, else the template's
    exclusive: bool                 # the basis is the character's exclusive arc (a row of the arc efficiency table)
    nodes: tuple                    # ordinary awakening effects in the data ("Effect1".."Effect6")
    template: tuple                 # the graduation template's selected effects
    template_level: int

    @property
    def seed_key(self) -> dict:
        """What the precomputed rows depend on besides the identity (compared with the seed's CHARACTERS)."""
        return {"fork": self.fork_id, "nodes": tuple(self.nodes), "template": tuple(self.template),
                "template_level": int(self.template_level)}


def eligible_characters(static_path) -> list[AwakeningEntry]:
    """Characters with a graduation template and an approved rotation, in character id order."""
    con = aes._ro(static_path)
    try:
        forks = []
        for fid, exclusive in con.execute("SELECT fork_id, exclusive_character_ids_json FROM fork_item"):
            try:
                owners = tuple(str(o) for o in (json.loads(exclusive or "[]") or ()))
            except (TypeError, ValueError):
                owners = ()
            forks.append((str(fid), owners))
        rows = con.execute(
            "SELECT g.character_id, c.name_zh, g.fork_id, g.profile_json FROM character_graduation_template g "
            "JOIN character c USING(character_id) ORDER BY g.character_id").fetchall()
        effects: dict[int, list] = {}
        for cid, effect_id in con.execute(
                "SELECT character_id, effect_id FROM character_awaken_effect WHERE awaken_type='Awaken_Effect' "
                "ORDER BY character_id, ordinal"):
            canonical = ta.node_id(effect_id)
            if canonical in NODES:
                effects.setdefault(int(cid), []).append(canonical)
        from src.services import team_cycle_reactions as tcr

        rules = tcr.load_rules(con)
    finally:
        con.close()
    out = []
    for cid, name, template_fork, profile_json in rows:
        cid = int(cid)
        if not aes._approved(cid):
            continue
        own = sorted(f for f, owners in forks if str(cid) in owners)    # ids are JSON strings: never compare as int
        basis = (template_fork if template_fork in own else own[0]) if own else str(template_fork or "")
        try:
            profile = json.loads(profile_json or "{}")
        except (TypeError, ValueError):
            profile = {}
        selection = ta.from_profile(profile)
        role, confidence = aes._rotation_info(cid)
        try:
            element = str(rules.element(cid) or "")
        except Exception:
            element = ""
        nodes = tuple(n for n in NODES if n in set(effects.get(cid, ())))
        out.append(AwakeningEntry(cid, str(name), element, role, confidence, str(basis), bool(own), nodes,
                                  tuple(selection.effects), int(selection.level)))
    return out


def fork_names(static_path, fork_ids: Iterable[str]) -> dict[str, str]:
    """{fork id: Chinese name} (the basis arcs' names for the page)."""
    wanted = sorted({str(f) for f in fork_ids if f})
    if not wanted:
        return {}
    con = aes._ro(static_path)
    try:
        marks = ",".join("?" * len(wanted))
        return {str(f): str(n or f) for f, n in
                con.execute(f"SELECT fork_id, name_zh FROM fork_item WHERE fork_id IN ({marks})", wanted)}
    finally:
        con.close()


def jobs_of(entry: AwakeningEntry) -> list[str]:
    """Variants in computing order: A0 and A6 (the two bases), add-one, the resonances, remove-one.  An effect the
    data lacks has no add-one run; an effect outside the template's selection has no remove-one run."""
    jobs = ["A0", "A6"]
    jobs.extend(f"+{n}" for n in NODES if n in entry.nodes)
    jobs.extend(("R3", "R6"))
    jobs.extend(f"-{n}" for n in NODES if n in entry.template)
    return jobs


def variant_spec(entry: AwakeningEntry, variant: str):
    """``team_simulation_service.MemberSpec`` of one variant (basis arc at refinement 1)."""
    from src.services import team_simulation_service as svc

    base = dict(fork_id=entry.fork_id, fork_refinement_level=1)
    if variant == "A6":            # the template's own selection: exactly the arc table's row
        return svc.MemberSpec(entry.character_id, **base)
    if variant == "A0":
        return svc.MemberSpec(entry.character_id, awakening_level=0, awakening_effects=(), **base)
    if variant in ("R3", "R6"):
        return svc.MemberSpec(entry.character_id, awakening_level=int(variant[1]), awakening_effects=(), **base)
    if variant[:1] == "+" and variant[1:] in NODES:
        return svc.MemberSpec(entry.character_id, awakening_level=1, awakening_effects=(variant[1:],), **base)
    if variant[:1] == "-" and variant[1:] in NODES:
        effects = tuple(n for n in entry.template if n != variant[1:])
        return svc.MemberSpec(entry.character_id, awakening_level=max(int(entry.template_level), len(effects)),
                              awakening_effects=effects, **base)
    raise ValueError(f"unknown variant {variant!r}")


# ── one character ─────────────────────────────────────────────────────────────

Row = aes.Row


def row_key(cid: int, variant: str, loops: int, entry: str = ENTRY) -> tuple:
    return (int(cid), str(variant), int(loops), str(entry))


class Cancelled(aes.Cancelled):
    pass


def compute_character(static_path, entry: AwakeningEntry, loops: int, variants: Iterable[str] | None = None, *,
                      cancel=None, on_row: Callable[[tuple, Row], None] | None = None, user_db_path=None,
                      template_level: int = 0) -> dict[tuple, Row]:
    """Run every variant of ``variants`` (default ``jobs_of``) on one shared ``solo_session``; ``on_row(key, row)``
    after each run; ``cancel`` (anything with ``is_set()``) is checked before every run (``Cancelled``).  Row
    values and flags as the arc table (``arc_efficiency_service.row_from_run``).  Empty account; with
    ``template_level`` > 0 an empty account holding only that Puka Boot Camp level (decision U1)."""
    from src.services import team_fork_corrections as tfc
    from src.services import team_simulation_service as svc

    jobs = list(jobs_of(entry) if variants is None else variants)
    out: dict[tuple, Row] = {}
    if not jobs:
        return out
    con = aes._ro(static_path)
    try:
        permanent = tuple(p for p, _v in tfc.load_permanent(con, entry.fork_id, 1))
    finally:
        con.close()
    with aes._COMPUTE_LOCK:
        if cancel is not None and cancel.is_set():
            raise Cancelled()
        with contextlib.ExitStack() as stack:
            if int(template_level or 0) > 0 and user_db_path is None:
                from src.services.puka_training_settings_service import template_account_database

                folder = stack.enter_context(tempfile.TemporaryDirectory(prefix="nte_awk_eff_tpl_",
                                                                         ignore_cleanup_errors=True))
                user_db_path = template_account_database(folder, int(template_level))
            run = stack.enter_context(svc.solo_session(static_path, entry.character_id, loops=loops,
                                                       user_db_path=user_db_path, account_id="awakening_efficiency"))
            for variant in jobs:
                if cancel is not None and cancel.is_set():
                    raise Cancelled()
                solo = run(variant_spec(entry, variant))
                key = row_key(entry.character_id, variant, loops)
                row = aes.row_from_run(solo, permanent)
                out[key] = row
                if on_row is not None:
                    on_row(key, row)
    return out


