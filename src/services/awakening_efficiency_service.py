def load_node_catalog(static_path, character_ids: Iterable[int] | None = None) -> dict[int, dict]:
    """{cid: {node id: effect row}} (title, description, template values) from the team simulator's catalog;
    resonances under ``resonance_3`` / ``resonance_6``."""
    from src.services import team_simulation_service as svc

    out: dict[int, dict] = {}
    for cid, effects in svc.awaken_effect_catalog(static_path, character_ids).items():
        table = {}
        for effect in effects:
            node = ta.node_id(effect.get("effect_id"))        # "Effect3" / "resonance_6" (DB effect ids)
            if node is not None:
                table[node] = effect
        out[int(cid)] = table
    return out
