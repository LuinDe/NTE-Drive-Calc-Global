def _force_stale() -> bool:
    return str(os.environ.get(FORCE_STALE_ENV, "")).strip() not in ("", "0", "false", "no", "off")


def _seed_character_matches(info: Mapping, entry: AwakeningEntry) -> bool:
    if not info:
        return False
    want = entry.seed_key
    return (str(info.get("fork", "")) == want["fork"] and tuple(info.get("nodes", ())) == want["nodes"]
            and tuple(info.get("template", ())) == want["template"]
            and int(info.get("template_level", -1)) == want["template_level"])


