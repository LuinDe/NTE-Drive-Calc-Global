def node_info(cid: int, node: str):
    """The node rules' metadata of one node (None when nothing is declared)."""
    try:
        from src.services.awakening_node_rules import core

        return core.node_info(int(cid), node)
    except Exception:
        return None


def node_class(info) -> str:
    """Cell class of a node from its metadata (user decision 2026-10-18).  Not priced -> never a number."""
    if info is None:
        return CLASS_MEASURE
    category, bucket = str(info.category), str(info.bucket)
    if category == "review":
        return CLASS_REVIEW
    if category == "bound":
        return CLASS_BOUND
    if bucket == "not_computable":
        return CLASS_NOT_COMPUTABLE
    if bucket == "measure":
        return CLASS_MEASURE
    if category in ("damage", "time", "cap"):
        return CLASS_EXPECTED if bool(info.expected_value) else CLASS_DAMAGE
    if category in ("team", "resource", "rotation"):
        return CLASS_TEAM
    if category == "none":
        return CLASS_NOT_COMPUTABLE
    return CLASS_MEASURE


def dps(row: Row | None) -> float | None:
    if row is None or row.active_us <= 0:
        return None
    return row.damage / (row.active_us / 1e6)


@dataclass(frozen=True)
class Change:
    """One pair (numerator / denominator variant)."""
    pct: float | None               # DPS change %
    damage_pct: float | None        # damage change %
    end_delta_s: float | None       # numerator end - denominator end (s)
    time_changed: bool

    @property
    def shown(self) -> bool:
        return self.pct is not None and abs(self.pct) >= ZERO_PCT


def change(num: Row | None, den: Row | None) -> Change:
    a, b = dps(num), dps(den)
    if a is None or b is None or b <= 0:
        return Change(None, None, None, False)
    damage = 100.0 * (num.damage / den.damage - 1.0) if den.damage > 0 else None
    delta = num.end_us - den.end_us
    return Change(100.0 * (a / b - 1.0), damage, delta / 1e6, abs(delta) >= TIME_US)


@dataclass
class Cell:
    column: str                     # Effect1..Effect6 | resonance_3 | resonance_6 | full
    cls: str                        # cell class (CELL_CLASSES)
    value: Change                   # the shown basis
    other: Change | None            # ordinary effects: the other basis
    loops: int
    info: Any = None                # NodeInfo (None for "full")
    reference: Mapping | None = None    # hand-kept reference values (awakening_efficiency_notes.REFERENCE)
    pending: bool = False
    mismatch: bool = False          # a number where the class says "not priced": the metadata needs a look
    partial_nodes: tuple = ()       # full / resonance 3: selected nodes whose solo effect is not computed
    #                                 (needs measurement / under review / upper bound)

    @property
    def numeric(self) -> bool:
        """The cell shows a number: a priced class, the full column, or resonance 3's skill level part."""
        if self.cls in NUMERIC_CLASSES or self.column == "full":
            return True
        return self.column == "resonance_3" and self.value.shown


@dataclass
class MatrixRow:
    entry: AwakeningEntry
    loops: int
    basis: str
    cells: dict
    a0: Row | None
    a6: Row | None
    complete: bool
    failed: bool
    sum_single: float | None        # sum of the add-one values of the priced effects (the full cell's tooltip)


def reference_of(cid: int, node: str) -> Mapping | None:
    try:
        from src.services import awakening_efficiency_notes as notes

        return notes.REFERENCE.get((int(cid), str(node)))
    except Exception:
        return None


def build_matrix(entry: AwakeningEntry, rows: Mapping[tuple, Row], loops: int, basis: str = "add_one"
                 ) -> MatrixRow:
    """One table row: the cells of ``COLUMNS`` for ``basis`` (add_one / remove_one)."""
    cid = entry.character_id
    get = lambda v: rows.get(row_key(cid, v, loops))  # noqa: E731
    a0, a6, r3, r6 = get("A0"), get("A6"), get("R3"), get("R6")
    failed = (a0 is not None and a0.damage <= 0) or (a6 is not None and a6.damage <= 0)
    cells: dict[str, Cell] = {}
    unpriced = []
    singles = []
    for node in NODES:
        info = node_info(cid, node)
        cls = node_class(info)
        add = change(get(f"+{node}"), a0) if node in entry.nodes else Change(None, None, None, False)
        remove = change(a6, get(f"-{node}")) if node in entry.template else Change(None, None, None, False)
        shown, other = (add, remove) if basis == "add_one" else (remove, add)
        if basis == "add_one":
            pending = a0 is None or (node in entry.nodes and get(f"+{node}") is None)
        else:
            pending = a6 is None or (node in entry.template and get(f"-{node}") is None)
        numeric = cls in NUMERIC_CLASSES
        # a class that is not priced while the simulation moves: shown with the number and "check the class"
        # (under review: the engine prices a part on purpose, the number stays in the tooltip - design §3.3)
        mismatch = (not numeric and cls != CLASS_REVIEW and (add.shown or remove.shown))
        if cls in UNPRICED_CLASSES and node in entry.template:
            unpriced.append(node)
        if numeric and add.pct is not None:
            singles.append(add.pct)
        cells[node] = Cell(node, cls, shown, other, loops, info, reference_of(cid, node), pending, mismatch)
    for node, num, den in (("resonance_3", r3, a0), ("resonance_6", r6, r3)):
        info = node_info(cid, node)
        cls = node_class(info)
        value = change(num, den)
        numeric = cls in NUMERIC_CLASSES
        # resonance 3 always carries the skill level +1 the engine prices: a number there is not a mismatch
        mismatch = (not numeric and cls != CLASS_REVIEW and value.shown and node != "resonance_3")
        partial = (node,) if (node == "resonance_3" and cls in UNPRICED_CLASSES) else ()
        cells[node] = Cell(node, cls, value, None, loops, info, reference_of(cid, node), num is None or den is None,
                           mismatch, partial)
    full_unpriced = tuple(unpriced) + tuple(n for n in RESONANCES if cells[n].cls in UNPRICED_CLASSES)
    cells["full"] = Cell("full", CLASS_DAMAGE, change(a6, a0), None, loops, None, None, a0 is None or a6 is None,
                         False, full_unpriced)
    complete = all(row_key(cid, v, loops) in rows for v in jobs_of(entry))
    return MatrixRow(entry, loops, basis, cells, a0, a6, complete, bool(failed),
                     sum(singles) if singles else None)


def order_entries(entries: Iterable[AwakeningEntry]) -> list[AwakeningEntry]:
    """The arc table's characters (exclusive arc) first, then the others, each in character id order."""
    items = list(entries)
    return sorted(items, key=lambda e: (not e.exclusive, e.character_id))


# ── preferences (account independent) ────────────────────────────────────────

DEFAULT_PREFERENCES = {"basis": "add_one", "collapsed": False, "split": None}


def load_preferences(path: Path | None) -> dict:
    prefs = dict(DEFAULT_PREFERENCES)
    if path is None:
        return prefs
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        if isinstance(data, dict):
            if data.get("basis") in BASES:
                prefs["basis"] = data["basis"]
            if isinstance(data.get("collapsed"), bool):
                prefs["collapsed"] = data["collapsed"]
            split = data.get("split")
            if isinstance(split, list) and len(split) == 2 and all(isinstance(v, int) and v >= 0 for v in split):
                prefs["split"] = [int(v) for v in split]
    except Exception:
        pass
    return prefs


def save_preferences(path: Path | None, prefs: Mapping[str, Any]) -> None:
    if path is None:
        return
    try:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(json.dumps({k: prefs.get(k) for k in DEFAULT_PREFERENCES}, ensure_ascii=False), encoding="utf-8")
        os.replace(tmp, path)
    except Exception as exc:  # noqa: BLE001
        aes._log(f"awakening efficiency preferences not saved: {type(exc).__name__}: {exc}")


