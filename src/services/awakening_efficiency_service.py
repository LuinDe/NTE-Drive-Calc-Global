# ── which layer serves a character ────────────────────────────────────────────

SOURCE_SEED = aes.SOURCE_SEED
SOURCE_CACHE = aes.SOURCE_CACHE
SOURCE_STALE = aes.SOURCE_STALE


def resolve(static_path, entries: Iterable[AwakeningEntry], loops: int, cache: Cache | None,
            identity: aes.Identity | None = None, module=...) -> aes.Resolution:
    """For every character: L1 when the seed's identity and the character's basis / effects / template match, else
    L2 when it holds every row, else stale (finished L2 rows are still returned)."""
    identity = identity or current_identity(static_path)
    module = seed() if module is ... else module
    force = _force_stale()
    ok_seed = (not force) and seed_matches(module, identity)
    seed_chars = getattr(module, "CHARACTERS", {}) if ok_seed else {}
    table = seed_rows(module, identity.template_level) if ok_seed else {}
    sources: dict[int, str] = {}
    rows: dict[tuple, Row] = {}
    stamps: dict[int, str] = {}
    for entry in entries:
        cid = entry.character_id
        keys = [row_key(cid, v, loops) for v in jobs_of(entry)]
        if ok_seed and _seed_character_matches(seed_chars.get(cid) or {}, entry) and all(k in table for k in keys):
            for k in keys:
                rows[k] = Row(*table[k])
            sources[cid] = SOURCE_SEED
            continue
        got = {k: cache.get(identity, k) for k in keys} if (cache is not None and not force) else {}
        if got and all(v is not None for v in got.values()):
            rows.update(got)
            sources[cid] = SOURCE_CACHE
            stamps[cid] = max((cache.computed_at(identity, k) for k in keys), default="")
        else:
            sources[cid] = SOURCE_STALE
            if not force:
                rows.update({k: v for k, v in got.items() if v is not None})
    return aes.Resolution(identity, sources, rows, stamps)


# ── background recomputation ──────────────────────────────────────────────────

class Computation:
    """Recompute stale characters in a worker thread (``run``), the viewed one first (``prioritize``), cancel within
    one run (``cancel``).  ``pending`` = {cid: [variant, ...]}.  Every finished row goes to the cache (memory) and to
    ``on_row``; the cache file is saved when a character finishes and when the computation stops.  A character whose
    A0 or A6 damage is 0 (or which fails) is not cached: ``on_character(cid, False, reason)``."""

    def __init__(self, static_path, entries: Mapping[int, AwakeningEntry], loops: int, pending: Mapping[int, list],
                 cache: Cache | None, identity: aes.Identity, *,
                 on_row: Callable[[tuple, Row], None] | None = None,
                 on_character: Callable[[int, bool, str], None] | None = None,
                 order: Iterable[int] | None = None, generation: int = 0, user_db_path=None) -> None:
        self.static_path = static_path
        self.entries = dict(entries)
        self.loops = int(loops)
        self.pending = {int(c): list(j) for c, j in pending.items() if j}
        self.cache = cache
        self.identity = identity
        self.on_row = on_row
        self.on_character = on_character
        self.order = [int(c) for c in (order if order is not None else self.pending)]
        self.generation = generation
        self.user_db_path = user_db_path
        self._cancel = threading.Event()
        self._priority: int | None = None
        self.done_rows: dict[tuple, Row] = {}
        self.runs = 0

    def cancel(self) -> None:
        self._cancel.set()

    @property
    def cancelled(self) -> bool:
        return self._cancel.is_set()

    def prioritize(self, cid: int | None) -> None:
        self._priority = None if cid is None else int(cid)

    def _next(self) -> int | None:
        if self._priority is not None and self.pending.get(self._priority):
            return self._priority
        for cid in self.order:
            if self.pending.get(cid):
                return cid
        return next((c for c, j in self.pending.items() if j), None)

    def _basis_ok(self, cid: int, rows: Mapping[tuple, Row]) -> bool:
        a0 = rows.get(row_key(cid, "A0", self.loops))
        a6 = rows.get(row_key(cid, "A6", self.loops))
        return a0 is not None and a6 is not None and a0.damage > 0 and a6.damage > 0

    def _finish(self, cid: int) -> None:
        rows = {k: v for k, v in self.done_rows.items() if k[0] == cid and k[2] == self.loops}
        ok = self._basis_ok(cid, rows)
        if ok and self.cache is not None:
            for key, row in rows.items():
                self.cache.put(self.identity, key, row)
            self.cache.save(self.identity)
        if self.on_character is not None:
            self.on_character(cid, ok, "" if ok else "basis")

    def run(self) -> dict[tuple, Row]:
        while not self._cancel.is_set():
            cid = self._next()
            if cid is None:
                break
            switch = threading.Event()
            gate = aes._Gate(self._cancel, switch)

            def watch(key, row, session_cid=cid):
                self.done_rows[key] = row
                self.runs += 1
                if key[1] in self.pending.get(session_cid, []):
                    self.pending[session_cid].remove(key[1])
                if self.on_row is not None:
                    self.on_row(key, row)
                wanted = self._priority
                if wanted is not None and wanted != session_cid and self.pending.get(wanted):
                    switch.set()          # the viewed character goes first: stop this session after this run

            try:
                compute_character(self.static_path, self.entries[cid], self.loops, list(self.pending[cid]),
                                  cancel=gate, on_row=watch, user_db_path=self.user_db_path,
                                  template_level=self.identity.template_level)
            except aes.Cancelled:
                pass
            except Exception as exc:  # noqa: BLE001 - one character failing never stops the others
                self.pending[cid] = []
                aes._log(f"awakening efficiency: {cid} failed: {type(exc).__name__}: {exc}")
                if self.on_character is not None:
                    self.on_character(cid, False, f"{type(exc).__name__}: {exc}")
                continue
            if not self.pending.get(cid):
                self._finish(cid)
        if self.cache is not None and self.done_rows:
            for cid in {k[0] for k in self.done_rows}:
                rows = {k: v for k, v in self.done_rows.items() if k[0] == cid}
                if self._basis_ok(cid, rows):
                    for key, row in rows.items():
                        self.cache.put(self.identity, key, row)
            self.cache.save(self.identity)
        return self.done_rows


